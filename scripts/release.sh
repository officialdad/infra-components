#!/usr/bin/env bash
# Cut a release in two steps. `main` only takes changes through a pull request, so the release
# commit is never pushed to it. Tags are not covered by that rule.
#
# 1. scripts/release.sh X.Y.Z            GENERATE the new CHANGELOG section from Conventional Commits
#    with git-cliff, splice it under `## [Unreleased]` as `## [X.Y.Z] - <today>`, fix the two compare
#    links, and commit `chore(release): vX.Y.Z` on the branch `release/vX.Y.Z`. LOCAL ONLY: nothing is
#    pushed and nothing is tagged. Review with `git show`. Undo before publishing:
#      git switch main && git branch -D release/vX.Y.Z
# 2. scripts/release.sh X.Y.Z --publish  push that branch, open a PR, squash-merge it, tag the MERGE
#    commit `vX.Y.Z` and push the tag (a pre-push guard checks the tag matches the CHANGELOG). The tag
#    push publishes the GitHub Release (changelog.yml).
#
# The release notes are GENERATED, not curated: git-cliff (config: cliff.toml) is the single source
# of truth and the same generator backs the GitHub Release, so CHANGELOG.md == the Release notes.
# History at v0.6.0 and older is frozen (it predates the commit gate) -- only the new section is
# generated and spliced; the existing sections are never rewritten.
#
# Requires: git-cliff on PATH (https://github.com/orhun/git-cliff -- see README "Toolchain");
# gh logged in for --publish.
#
# Usage: scripts/release.sh X.Y.Z [--dry-run | --publish]
#   --dry-run  print the generated section + CHANGELOG diff only; touch nothing, skip git-state checks.
#   --publish  step 2. Run it on the branch step 1 created.
set -euo pipefail

die() { printf 'release: %s\n' "$1" >&2; exit 1; }

ver="${1:-}"
dry=0
publish=0
case "${2:-}" in
  "") ;;
  --dry-run) dry=1 ;;
  --publish) publish=1 ;;
  *) die "unknown option '$2' -- usage: scripts/release.sh X.Y.Z [--dry-run | --publish]" ;;
esac
[ -n "$ver" ] || die "usage: scripts/release.sh X.Y.Z [--dry-run | --publish]"
printf '%s' "$ver" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$' \
  || die "version must be X.Y.Z with no leading 'v' (got '$ver')"

branch="release/v$ver"

# --- step 2: publish --------------------------------------------------------------------------
if [ "$publish" -eq 1 ]; then
  command -v gh >/dev/null 2>&1 || die "gh not found -- --publish opens a pull request (https://cli.github.com)"
  gh auth status >/dev/null 2>&1 || die "gh is not logged in -- --publish opens a pull request (gh auth login)"
  root="$(git rev-parse --show-toplevel)" || die "not in a git repo"
  cd "$root"
  [ "$(git rev-parse --abbrev-ref HEAD)" = "$branch" ] \
    || die "run --publish on the branch $branch that 'scripts/release.sh $ver' created (you are on $(git rev-parse --abbrev-ref HEAD))"
  [ -z "$(git status --porcelain)" ] || die "working tree not clean -- commit or stash first"
  [ "$(git log -1 --format=%s)" = "chore(release): v$ver" ] \
    || die "the tip of $branch is not the release commit 'chore(release): v$ver'"
  git ls-remote --exit-code --tags origin "refs/tags/v$ver" >/dev/null 2>&1 && die "tag v$ver already exists on origin"

  git push -u origin "$branch"
  body="$(mktemp)"
  cat >"$body" <<BODY
## Summary

Release v$ver: the generated CHANGELOG section and compare links. Opened by \`scripts/release.sh\`.
The script tags the merge commit after this PR merges. The tag push publishes the GitHub Release.

## Component(s)

repo-wide

## Type

- [x] Release commit, no module change

## Changes

- \`CHANGELOG.md\`: new \`## [$ver]\` section generated by git-cliff

## Validation

- [x] Section generated by \`scripts/release.sh $ver\`; the pre-push guard checks it against the tag
BODY
  pr_url="$(gh pr create --base main --head "$branch" --title "chore(release): v$ver" --body-file "$body")"
  rm -f "$body"
  printf 'Opened %s\n' "$pr_url"

  # Merge now when nothing blocks it. If a required check is still running, queue the merge instead.
  gh pr merge "$pr_url" --squash 2>/dev/null || gh pr merge "$pr_url" --squash --auto

  printf 'Waiting for the PR to merge'
  merge_sha=""
  for _ in $(seq 1 240); do
    state=""
    merge_sha=""
    read -r state merge_sha < <(gh pr view "$pr_url" --json state,mergeCommit --jq '.state + " " + (.mergeCommit.oid // "")') || true
    [ "$state" = "MERGED" ] && break
    [ "$state" = "CLOSED" ] && { printf '\n'; die "the PR was closed without merging: $pr_url"; }
    merge_sha=""
    printf '.'; sleep 5
  done
  printf '\n'
  [ -n "$merge_sha" ] \
    || die "the PR did not merge within 20 minutes: $pr_url -- once it merges, tag by hand: git fetch origin && git tag -m 'Release v$ver' v$ver <merge-sha> && git push origin v$ver"

  # Tag the merge commit itself, not whatever main points at now: another PR may have landed since.
  git fetch -q origin main
  git tag -m "Release v$ver" "v$ver" "$merge_sha"
  git push origin "v$ver"

  # The release is out; cleanup is best effort.
  { git switch -q main && git merge -q --ff-only origin/main && git branch -q -D "$branch"; } || true
  git push -q origin --delete "$branch" 2>/dev/null || true
  printf '\n✓ Released v%s: %s\n' "$ver" "$pr_url"
  exit 0
fi

command -v git-cliff >/dev/null 2>&1 \
  || die "git-cliff not found on PATH -- install it (see README 'Toolchain'); release notes are generated from commits"

root="$(git rev-parse --show-toplevel)" || die "not in a git repo"
cd "$root"
cl="CHANGELOG.md"
[ -f "$cl" ] || die "$cl not found"

# Generate the new version's section from the unreleased Conventional Commits. git-cliff dates the
# unreleased-as-vX.Y.Z block with TODAY (verified: not the last-commit date), so no date surgery is
# needed. `--strip header` keeps only the section body. Trailing blank lines are trimmed so the
# splice leaves exactly one blank line before the previous version.
section_file="$(mktemp)"
gen_err="$(mktemp)"
if ! git-cliff --config cliff.toml --unreleased --tag "v$ver" --strip header >"$section_file.raw" 2>"$gen_err"; then
  cat "$gen_err" >&2; rm -f "$section_file" "$section_file.raw" "$gen_err"; die "git-cliff failed to generate the changelog section"
fi
awk '{ a[NR] = $0 } END { last = NR; while (last > 0 && a[last] == "") last--; for (i = 1; i <= last; i++) print a[i] }' \
  "$section_file.raw" >"$section_file"
rm -f "$section_file.raw" "$gen_err"

# A release whose only commits are chore/ci/docs/etc. produces a heading with no entries -- there is
# nothing consumer-facing to release.
grep -Eq '^(### |- )' "$section_file" \
  || { rm -f "$section_file"; die "no consumer-facing changes since the last tag (only skipped commit types) -- nothing to release"; }

# Splice the generated section under `## [Unreleased]` and rewrite the two compare links. The
# previous tag is read from the existing [Unreleased] compare link (trust the file, not `git tag`).
splice() { # splice <changelog-in> <section-file> <out>
  awk -v ver="$ver" -v secfile="$2" '
    !spliced && /^## \[Unreleased\]$/ {
      print; print ""
      while ((getline line < secfile) > 0) print line
      close(secfile)
      spliced = 1; next
    }
    /^\[Unreleased\]:[[:space:]]/ && index($0, "/compare/") > 0 {
      ci = index($0, "/compare/"); prefix = substr($0, 1, ci - 1)
      sub(/^\[Unreleased\]:[[:space:]]*/, "", prefix)
      rest = substr($0, ci + 9); di = index(rest, "..."); oldbase = substr(rest, 1, di - 1)
      print "[Unreleased]: " prefix "/compare/v" ver "...HEAD"
      print "[" ver "]: " prefix "/compare/" oldbase "...v" ver
      next
    }
    { print }
  ' "$1" >"$3"
}

if [ "$dry" -eq 1 ]; then
  printf '=== generated section (v%s) ===\n' "$ver"
  cat "$section_file"
  printf '\n=== CHANGELOG.md diff ===\n'
  tmp="$(mktemp)"
  splice "$cl" "$section_file" "$tmp"
  diff -u "$cl" "$tmp" | sed "s#$tmp#CHANGELOG.md (released v$ver)#" || true
  rm -f "$tmp" "$section_file"
  exit 0
fi

# --- preconditions (real run) ----------------------------------------------------------------
[ "$(git rev-parse --abbrev-ref HEAD)" = "main" ] || die "must be on 'main' (you are on $(git rev-parse --abbrev-ref HEAD))"
[ -z "$(git status --porcelain)" ] || die "working tree not clean -- commit or stash first"
git rev-parse -q --verify "refs/tags/v$ver" >/dev/null && die "tag v$ver already exists"
git rev-parse -q --verify "refs/heads/$branch" >/dev/null && die "branch $branch already exists -- publish it, or delete it: git branch -D $branch"
if git fetch -q origin main 2>/dev/null; then
  [ "$(git rev-parse HEAD)" = "$(git rev-parse origin/main)" ] \
    || die "local main is behind/ahead of origin/main -- sync first"
fi

# --- do it -----------------------------------------------------------------------------------
git switch -q -c "$branch"
splice "$cl" "$section_file" "$cl.tmp"
mv "$cl.tmp" "$cl"
rm -f "$section_file"
git --no-pager diff -- "$cl"
git add "$cl"
git commit -m "chore(release): v$ver"

cat <<EOF

✓ Release commit for v$ver is on branch $branch. Nothing pushed, nothing tagged yet.
  review : git show
  publish: scripts/release.sh $ver --publish   # PR -> squash merge -> tag the merge commit
  undo   : git switch main && git branch -D $branch
EOF
